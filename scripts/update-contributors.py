#!/usr/bin/env python3
"""Regenerate the contributor list shown on the About page.

The release workflow runs this once per release, so every package of that
release carries the same list. If GitHub cannot be reached the list already
in the repository is kept: a release never fails over the About page.
"""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import urllib.request

REPOSITORY = 'anvildroid/anvildroid'
ROOT = Path(__file__).resolve().parent.parent
COMMITTED = ROOT / 'crates/anvildroid-gui/src-frontend/contributors.js'
LOGIN = re.compile(r'[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?')


def logins(entries):
    """People in GitHub's order (most commits first); bots and odd names are left out."""
    names = []
    for entry in entries:
        login = entry.get('login') if isinstance(entry, dict) else None
        if (isinstance(login, str) and entry.get('type') == 'User' and LOGIN.fullmatch(login)
                and login not in names):
            names.append(login)
    return names


def fetch():
    entries, headers = [], {'Accept': 'application/vnd.github+json', 'User-Agent': 'AnvilDroid-release'}
    token = os.environ.get('GH_TOKEN') or os.environ.get('GITHUB_TOKEN')
    if token: headers['Authorization'] = 'Bearer ' + token
    for page in range(1, 6):
        request = urllib.request.Request(
            f'https://api.github.com/repos/{REPOSITORY}/contributors?per_page=100&page={page}', headers=headers)
        with urllib.request.urlopen(request, timeout=30) as response:
            batch = json.load(response)
        if not isinstance(batch, list): raise ValueError('Unexpected contributor response')
        entries += batch
        if len(batch) < 100: break
    return entries


def render(names):
    return ('// Generated by scripts/update-contributors.py at each release; do not edit by hand.\n'
            f'const ANVIL_CONTRIBUTORS = {json.dumps(names)};\n'
            "if (typeof module !== 'undefined') module.exports = ANVIL_CONTRIBUTORS;\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=COMMITTED)
    parser.add_argument('--source', type=Path, help='read the GitHub contributor JSON from a file instead of the network')
    arguments = parser.parse_args()
    try:
        names = logins(json.loads(arguments.source.read_text()) if arguments.source else fetch())
        if not names: raise ValueError('No contributors found')
        text = render(names)
    except (OSError, ValueError) as error:
        print(f'Keeping the committed contributor list: {error}', file=sys.stderr)
        text = COMMITTED.read_text()
    arguments.output.write_text(text)
    print(arguments.output)


if __name__ == '__main__':
    main()
