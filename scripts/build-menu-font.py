#!/usr/bin/env python3
"""Generate the bridge menu's antialiased Noto Sans glyph atlas.

The generated header is checked in; runtime/builds need no host font library.
Regenerate with Pillow and the OFL-licensed NotoSans-Regular.ttf (14/11px).
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font', type=Path, default=Path('/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf'))
parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'native/bridge/menu-font-data.h')
args = parser.parse_args()
rows = ['/* Generated by scripts/build-menu-font.py; Noto Sans Regular, OFL-1.1.',
        ' * Font SHA256: ' + hashlib.sha256(args.font.read_bytes()).hexdigest(),
        ' * Copyright Google Inc./Google LLC. See native/menu-font-OFL.txt. */',
        '#ifndef ANVILDROID_MENU_FONT_DATA_H', '#define ANVILDROID_MENU_FONT_DATA_H',
        'struct menu_glyph { unsigned short offset; unsigned char w,h,advance; signed char x,y; };']
for size in (14, 11):
    font = ImageFont.truetype(str(args.font), size)
    data, glyphs = [], []
    for code in range(32, 127):
        char = chr(code)
        left, top, right, bottom = font.getbbox(char, anchor='ls')
        w, h = right-left, bottom-top
        glyphs.append((len(data), w, h, round(font.getlength(char)), left, top))
        if w and h:
            mask = Image.new('L', (w,h))
            ImageDraw.Draw(mask).text((-left,-top),char,font=font,fill=255,anchor='ls')
            data.extend(mask.tobytes())
    assert len(data) < 65536
    rows += [f'static const unsigned char menu_alpha_{size}[] = {{']
    rows += ['  '+','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32)]
    rows += ['};',f'static const struct menu_glyph menu_glyphs_{size}[95] = {{']
    rows += ['  {'+','.join(map(str,g))+'},' for g in glyphs]
    rows += ['};']
rows += ['#endif','']
args.output.write_text('\n'.join(rows))
